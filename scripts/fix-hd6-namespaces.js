#!/usr/bin/env node
/**
 * scripts/fix-hd6-namespaces.js — §13.10 cleanup
 *
 * Renames two HD6 apps' UI5 namespaces to match the project convention
 * com.erpis.shiperp.{app}.hd6:
 *
 *   parceldemohd6:
 *     com.erpis.shiperp.parcel        → com.erpis.shiperp.parceldemo.hd6
 *     com/erpis/shiperp/parcel        → com/erpis/shiperp/parceldemo/hd6
 *
 *   farpthd6:
 *     com.erpis.testfarptFA_RPT.hd6   → com.erpis.shiperp.farpt.hd6
 *     com.erpis.testfarptFA_RPT       → com.erpis.shiperp.farpt
 *     com/erpis/testfarptFA_RPT/hd6   → com/erpis/shiperp/farpt/hd6
 *     com/erpis/testfarptFA_RPT       → com/erpis/shiperp/farpt
 *
 * Touches source files (Component.js, controller/*.js, view/*.xml,
 * fragment/*.xml, common/, model/, index.html, manifest.json) AND
 * the prebuilt artifacts (Component-preload*.js, *.js.map, *-dbg.js).
 * The /dist tree is regenerated by `mbt build`, so we skip it.
 *
 * Path renames before namespace renames so we don't accidentally
 * double-rewrite (paths use `/`, namespaces use `.`, so they don't
 * overlap, but ordering it this way keeps the diffs readable).
 *
 * Run from repo root:  node scripts/fix-hd6-namespaces.js
 */
const fs = require("fs");
const path = require("path");

const APPS = [
  {
    dir: "apps/parceldemohd6",
    replacements: [
      // path-form first
      [/com\/erpis\/shiperp\/parcel\b/g, "com/erpis/shiperp/parceldemo/hd6"],
      // dotted-form
      [/com\.erpis\.shiperp\.parcel\b/g, "com.erpis.shiperp.parceldemo.hd6"],
    ],
  },
  {
    dir: "apps/farpthd6",
    replacements: [
      [/com\/erpis\/testfarptFA_RPT\/hd6\b/g, "com/erpis/shiperp/farpt/hd6"],
      [/com\/erpis\/testfarptFA_RPT\b/g, "com/erpis/shiperp/farpt"],
      [/com\.erpis\.testfarptFA_RPT\.hd6\b/g, "com.erpis.shiperp.farpt.hd6"],
      [/com\.erpis\.testfarptFA_RPT\b/g, "com.erpis.shiperp.farpt"],
    ],
  },
];

const EXTS = new Set([".js", ".xml", ".html", ".json", ".properties", ".map"]);

function walk(dir, files = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.name === "node_modules" || entry.name === "dist") continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full, files);
    else if (EXTS.has(path.extname(entry.name))) files.push(full);
  }
  return files;
}

let totalEdits = 0;
for (const { dir, replacements } of APPS) {
  if (!fs.existsSync(dir)) {
    console.log(`SKIP ${dir} — directory missing`);
    continue;
  }
  const files = walk(dir);
  let appEdits = 0;
  for (const f of files) {
    let text;
    try {
      text = fs.readFileSync(f, "utf8");
    } catch {
      continue;
    }
    let next = text;
    for (const [pat, rep] of replacements) next = next.replace(pat, rep);
    if (next !== text) {
      fs.writeFileSync(f, next, "utf8");
      appEdits++;
      console.log(`  edited ${f}`);
    }
  }
  console.log(`${dir}: ${appEdits} file(s) edited`);
  totalEdits += appEdits;
}
console.log(`\nTotal: ${totalEdits} file(s) edited across ${APPS.length} app(s).`);
